"""Sector reports: 10 sector PDFs."""
import pathlib, sqlite3
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer, Image
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.lib.enums import TA_CENTER
import tempfile

DB_PATH = pathlib.Path("data/nifty100.db")
OUTPUT_DIR = pathlib.Path("reports/sector")
NAVY = colors.HexColor("#0f2a44")

def _chart(fig):
    tmp = tempfile.NamedTemporaryFile(suffix=".png", delete=False)
    fig.savefig(tmp.name, dpi=120, bbox_inches="tight")
    plt.close(fig)
    return tmp.name

def generate_sector_report(sector_name, output_path=None):
    con = sqlite3.connect(str(DB_PATH))
    comps = pd.read_sql("SELECT * FROM companies WHERE broad_sector=?", con, params=(sector_name,))
    if comps.empty:
        con.close()
        return None
    cids = comps["company_id"].tolist()
    placeholders = ",".join(["?"]*len(cids))
    fr = pd.read_sql(f"SELECT * FROM financial_ratios WHERE company_id IN ({placeholders})", con, params=cids)
    con.close()
    if output_path is None:
        OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
        safe = sector_name.replace(" ","_")
        output_path = OUTPUT_DIR / f"{safe}_sector_report.pdf"

    doc = SimpleDocTemplate(str(output_path), pagesize=A4, topMargin=10*mm)
    styles = getSampleStyleSheet()
    title = ParagraphStyle("title", parent=styles["Heading1"], textColor=colors.white, alignment=TA_CENTER)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], textColor=NAVY, fontSize=11)
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=7, leading=8)

    story=[]
    hdr = [[Paragraph(f"<b>{sector_name} — Sector Report</b> ({len(comps)} companies)", title)]]
    tbl = Table(hdr, colWidths=[190*mm])
    tbl.setStyle(TableStyle([("BACKGROUND",(0,0),(-1,-1), NAVY), ("TOPPADDING",(0,0),(-1,-1),6), ("BOTTOMPADDING",(0,0),(-1,-1),6)]))
    story.append(tbl)
    story.append(Spacer(1,4*mm))
    # summary stats
    latest = fr.copy()
    if not latest.empty:
        latest["year_int"] = pd.to_numeric(latest["year"], errors="coerce")
        latest = latest.sort_values("year_int").groupby("company_id").tail(1)
        avg_roe = latest["return_on_equity_pct"].mean()
        avg_roce = latest["return_on_capital_employed_pct"].mean()
        avg_de = latest["debt_to_equity"].mean()
        story.append(Paragraph(f"Avg ROE {avg_roe:.1f}% | Avg ROCE {avg_roce:.1f}% | Avg D/E {avg_de:.2f} | Companies: {len(comps)}", small))
    story.append(Spacer(1,3*mm))

    # bubble chart: ROE vs ROCE size = sales? use net margin
    if not latest.empty:
        fig, ax = plt.subplots(figsize=(6,3.5))
        sc = ax.scatter(latest["return_on_equity_pct"], latest["return_on_capital_employed_pct"], s= (latest["net_profit_margin_pct"].fillna(5).clip(1,30)*10), alpha=0.6, c="#4a90e2", edgecolors="k")
        for _, r in latest.iterrows():
            ax.annotate(r["company_id"], (r["return_on_equity_pct"], r["return_on_capital_employed_pct"]), fontsize=6)
        ax.set_xlabel("ROE %")
        ax.set_ylabel("ROCE %")
        ax.set_title(f"{sector_name}: ROE vs ROCE (bubble = NPM)")
        plt.tight_layout()
        img = _chart(fig)
        story.append(Image(img, width=170*mm, height=80*mm))
        story.append(Spacer(1,4*mm))

    # table top companies
    if not latest.empty:
        top = latest.sort_values("return_on_equity_pct", ascending=False).head(10)
        data = [[Paragraph(f"<font size=6><b>{c}</b></font>", small) for c in ["Ticker","ROE %","ROCE %","D/E"]]]
        for _, r in top.iterrows():
            data.append([
                Paragraph(f"<font size=6>{r['company_id']}</font>", small),
                Paragraph(f"<font size=6>{r['return_on_equity_pct']:.1f}</font>", small) if pd.notna(r['return_on_equity_pct']) else Paragraph("<font size=6>-</font>", small),
                Paragraph(f"<font size=6>{r['return_on_capital_employed_pct']:.1f}</font>", small) if pd.notna(r['return_on_capital_employed_pct']) else Paragraph("<font size=6>-</font>", small),
                Paragraph(f"<font size=6>{r['debt_to_equity']:.2f}</font>", small) if pd.notna(r['debt_to_equity']) else Paragraph("<font size=6>-</font>", small),
            ])
        t = Table(data, colWidths=[50*mm,40*mm,40*mm,40*mm])
        t.setStyle(TableStyle([("GRID",(0,0),(-1,-1),0.5, colors.grey), ("BACKGROUND",(0,0),(-1,0), colors.lightgrey)]))
        story.append(t)

    story.append(Spacer(1,6*mm))
    story.append(Paragraph("Generated by Financial Intelligence Platform — Sector Insights", small))
    doc.build(story)
    return str(output_path)

def batch_generate():
    con = sqlite3.connect(str(DB_PATH))
    sectors = pd.read_sql("SELECT DISTINCT broad_sector FROM companies", con)["broad_sector"].tolist()
    con.close()
    for s in sectors:
        try:
            generate_sector_report(s)
            print(f"Sector {s} done")
        except Exception as e:
            print(f"Failed {s}: {e}")

if __name__ == "__main__":
    batch_generate()
